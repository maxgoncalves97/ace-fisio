import { test, expect, API, UI, login, nav, ymd } from './fixtures';

test('PAY-01 manual payment remains pending until professional records payment; patient sees both states', async ({ page, browser, clinic }, testInfo) => {
  const patient = await clinic.createPatient();
  const description = `E2E-payment-${clinic.unique}`;
  await login(page, clinic.professionalEmail);
  await page.goto(`/admin/patient/${patient.id}`);
  await page.getByTestId('tab-pagamentos').click();
  await page.getByTestId('new-payment').click();
  await page.getByTestId('pay-desc').fill(description);
  await page.getByTestId('pay-amount').fill('valor inválido');
  await page.getByTestId('save-payment').click();
  await expect(page.getByTestId('payment-error')).toContainText('Informe um valor válido');
  await page.getByTestId('pay-amount').fill('125,50');
  const saved = page.waitForResponse(r => r.url() === API + '/payments' && r.request().method() === 'POST');
  await page.getByTestId('save-payment').click();
  const response = await saved; expect(response.ok()).toBeTruthy();
  const payment = await response.json();
  expect(payment.amount).toBe(125.5);
  expect(payment.status).toBe('pendente');
  await expect(page.getByTestId(`pay-${payment.id}`)).toBeVisible();
  const context = await browser.newContext({ viewport: testInfo.project.use.viewport, isMobile: testInfo.project.use.isMobile, hasTouch: testInfo.project.use.hasTouch });
  try {
    const pp = await context.newPage();
    await login(pp, patient.email);
    await pp.goto(UI + '/patient/history');
    await pp.getByTestId('seg-pagamentos').click();
    await expect(pp.getByText(description, { exact: true }).locator('..')).toContainText('Pendente');
    await expect(pp.getByText(/125,50/)).toBeVisible();
    await page.getByTestId(`pay-${payment.id}`).click();
    await expect(page.getByTestId(`pay-${payment.id}`)).toHaveCount(0);
    await pp.reload();
    await pp.getByTestId('seg-pagamentos').click();
    await expect(pp.getByText(description, { exact: true }).locator('..')).toContainText('Pago');
    const persisted = await (await clinic.admin.get(API + `/payments?patient_id=${patient.id}`)).json();
    expect(persisted[0].status).toBe('pago');
    expect(persisted[0].paid_date).toBeTruthy();
  } finally { await context.close(); }
});

test('CONFIG-01 professional service price/duration and working hours persist and govern booking', async ({ page, clinic }) => {
  const patient = await clinic.createPatient();
  await login(page, clinic.professionalEmail);
  await nav(page, 'settings');
  const name = `E2E-service-${clinic.unique}`;
  await page.getByTestId('service-name').fill(name);
  await page.getByTestId('service-price').fill('150,50');
  await page.getByTestId('service-duration').fill('45');
  const created = page.waitForResponse(r => r.url() === API + '/professional-services' && r.request().method() === 'POST');
  await page.getByTestId('save-service').click();
  const response = await created; expect(response.ok()).toBeTruthy();
  const service = await response.json(); clinic.trackService(service);
  expect(service.price_cents).toBe(15050);
  expect(service.duration_min).toBe(45);
  await page.getByTestId('availability-start').fill('09:00');
  await page.getByTestId('availability-end').fill('17:00');
  const saved = page.waitForResponse(r => r.url() === API + '/professional-availability' && r.request().method() === 'PUT');
  await page.getByTestId('save-availability').click();
  expect((await saved).ok()).toBeTruthy();
  await page.reload();
  await expect(page.getByTestId('availability-start')).toHaveValue('09:00');
  await expect(page.getByTestId('availability-end')).toHaveValue('17:00');
  await expect(page.getByText(new RegExp(name))).toBeVisible();
  let workday = 7;
  while (['Sat', 'Sun'].includes(new Date(ymd(workday) + 'T12:00:00').toDateString().slice(0, 3))) workday++;
  const date = ymd(workday);
  const api = await clinic.patientApi(patient);
  const slots = await (await api.get(API + `/booking/slots?professional_id=${clinic.professionalId}&date=${date}&service_id=${service.id}`)).json();
  expect(slots[0]).toBe('09:00');
  expect(slots).not.toContain('16:30');
  expect(slots).not.toContain('08:30');
  const outside = await api.post(API + '/appointments', { data: { patient_id: patient.id, professional_id: clinic.professionalId, service_id: service.id, date, time: '08:00' } });
  expect(outside.status()).toBe(400);
  const booked = await api.post(API + '/appointments', { data: { patient_id: patient.id, professional_id: clinic.professionalId, service_id: service.id, date, time: '10:00', duration_min: 5, price_cents: 1 } });
  expect(booked.ok()).toBeTruthy();
  const appointment = await booked.json();
  expect(appointment.duration_min).toBe(45);
  expect(appointment.price_cents).toBe(15050);
});

test('NOTIFY-01 WhatsApp opt-in persists and revokes without claiming delivery', async ({ page, clinic }) => {
  const patient = await clinic.createPatient();
  await login(page, patient.email);
  const loaded = page.waitForResponse(r => r.url() === API + '/notification-preferences');
  await nav(page, 'notifications');
  expect((await loaded).ok()).toBeTruthy();
  await expect(page.getByText(/envio ainda não está ativo/)).toBeVisible();
  await page.getByTestId('whatsapp-consent').click();
  await page.getByTestId('whatsapp-phone').fill('5511999999999');
  let saved = page.waitForResponse(r => r.url() === API + '/notification-preferences/whatsapp' && r.request().method() === 'PUT');
  await page.getByTestId('save-whatsapp').click();
  expect((await (await saved).json()).enabled).toBe(true);
  await expect(page.getByText(/Preferência salva/)).toBeVisible();
  await page.reload();
  await expect(page.getByTestId('whatsapp-phone')).toHaveValue('5511999999999');
  await page.getByTestId('whatsapp-consent').click();
  await expect(page.getByTestId('whatsapp-phone')).toHaveCount(0);
  saved = page.waitForResponse(r => r.url() === API + '/notification-preferences/whatsapp' && r.request().method() === 'PUT');
  await page.getByTestId('save-whatsapp').click();
  const revoked = await (await saved).json();
  expect(revoked.enabled).toBe(false);
  expect(revoked.phone).toBe('');
  expect(revoked.whatsapp_status).toBe('requires_provider_setup');
});
